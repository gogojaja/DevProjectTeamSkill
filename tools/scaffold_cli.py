def _plan_files(name, layer, lang, adr_refs):
    cfg = LAYERS[layer]
    files = []
    if lang == "python":
        src_dir = f"src/{name}"
        for fname in cfg["python_files"]:
            gen = PY_GEN.get(fname)
            if gen:
                files.append((os.path.join(src_dir, fname), gen(name, adr_refs, layer)))
        for fname in cfg["test_files_py"]:
            gen = PY_TEST_GEN.get(fname)
            if gen:
                files.append((os.path.join(src_dir, fname), gen(name, adr_refs, layer)))
    elif lang == "typescript":
        src_dir = f"src/{name}"
        for tpl in cfg["ts_files"]:
            gen = TS_GEN.get(tpl)
            if gen:
                files.append((os.path.join(src_dir, tpl.replace("{name}", name)),
                              gen(name, adr_refs, layer)))
        for tpl in cfg["test_files_ts"]:
            gen = TS_TEST_GEN.get(tpl)
            if gen:
                files.append((os.path.join(src_dir, tpl.replace("{name}", name)),
                              gen(name, adr_refs, layer)))
    return files


def cmd_create(args):
    name, layer, lang = args.name, args.layer, args.lang
    adr_refs = [r.strip() for r in (args.adr_ref or "").split(",") if r.strip()]
    patterns = [p.strip() for p in (args.patterns or "").split(",") if p.strip()]
    dry_run = args.dry_run

    if layer not in LAYERS:
        print(f"[scaffold] Unknown layer '{layer}'. Choices: {', '.join(LAYERS.keys())}")
        return 1

    files = _plan_files(name, layer, lang, adr_refs)
    if not files:
        print(f"[scaffold] No templates for layer='{layer}' lang='{lang}'")
        return 1

    print(f"[scaffold] Module scaffold plan")
    print(f"  Module: {name}  Layer: {LAYERS[layer]['label']}  Lang: {lang}  Files: {len(files)}")
    if adr_refs:
        print(f"  ADR refs: {', '.join(adr_refs)}")
    if patterns:
        print(f"  Patterns: {', '.join(patterns)}")
    for path, _ in files:
        print(f"  {'[dry-run] ' if dry_run else ''}create {path}")

    if dry_run:
        print(f"\n[scaffold] dry-run complete, no files written")
        return 0

    written = 0
    for path, content in files:
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as f:
            f.write(content)
        written += 1
    print(f"\n[scaffold] Done: {written} files written")
    return 0


def cmd_templates(args):
    print("[scaffold] Available layer templates:")
    for key, cfg in LAYERS.items():
        print(f"\n  {key:14s} ({cfg['label']})")
        print(f"    Allowed deps: {', '.join(cfg['allowed_deps']) or 'none'}")
        print(f"    Python: {', '.join(cfg['python_files'])}")
        print(f"    TypeScript: {', '.join(cfg['ts_files'])}")
    print("\n[scaffold] Usage:")
    print("  python3 tools/scaffold_cli.py create --name orders --layer business --lang python")
    return 0


def main():
    ap = argparse.ArgumentParser(description="Module scaffold generator (T4)")
    sub = ap.add_subparsers(dest="command")
    cr = sub.add_parser("create", help="Generate module skeleton")
    cr.add_argument("--name", required=True)
    cr.add_argument("--layer", required=True, choices=LAYERS.keys())
    cr.add_argument("--lang", default="python", choices=["python", "typescript"])
    cr.add_argument("--patterns", default="")
    cr.add_argument("--adr-ref", default="")
    cr.add_argument("--dry-run", action="store_true")
    sub.add_parser("templates", help="List available templates")
    args = ap.parse_args()
    if args.command == "create":
        sys.exit(cmd_create(args))
    elif args.command == "templates":
        sys.exit(cmd_templates(args))
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
