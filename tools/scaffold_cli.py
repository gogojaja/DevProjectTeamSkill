def _class_name(name):
    return "".join(w.capitalize() for w in name.replace("-", "_").split("_"))


def _header_py(module, adr_refs, desc=""):
    lines = [f'"""{module} - {desc}', ""]
    if adr_refs:
        lines.append("Architecture constraints:")
        for ref in adr_refs:
            lines.append(f"  - {ref}")
    lines.extend(["", f"Generated by scaffold_cli on {datetime.date.today().isoformat()}", '"""', ""])
    return "\n".join(lines)


def _header_ts(module, adr_refs, desc=""):
    lines = [f"// {module} - {desc}"]
    if adr_refs:
        lines.append("// Architecture constraints: " + ", ".join(adr_refs))
    lines.extend([f"// Generated by scaffold_cli on {datetime.date.today().isoformat()}", ""])
    return "\n".join(lines)


